import re
import shutil
import stat
import subprocess

import deploy
import pytest
import yaml
from conftest import expect_exit, make_cfg, make_ctx


def mode(path):
    return stat.S_IMODE(path.stat().st_mode)


def test_render_one_substitutes(server_dir, raw):
    text = deploy._render_one("template/config.yaml.tmpl", "config.yaml",
                              make_cfg(raw).template_vars())
    assert 'exposedAddress: "https://netbird.example.com:443"' in text
    assert "${" not in text


def test_render_one_missing_var_exits_2(server_dir, raw, capsys):
    variables = make_cfg(raw).template_vars()
    del variables["NETBIRD_DOMAIN"]
    expect_exit(capsys, lambda: deploy._render_one(
        "template/config.yaml.tmpl", "config.yaml", variables), "${NETBIRD_DOMAIN}")


def test_render_one_rejects_leftover_placeholder(server_dir, raw, capsys):
    variables = make_cfg(raw).template_vars()
    variables["GITHUB_ORG"] = "${X}"
    expect_exit(capsys, lambda: deploy._render_one(
        "template/dex.config.yaml.tmpl", "dex/config.yaml", variables), "still contains")


def test_phase_render_modes(server_dir, raw):
    deploy.phase_render(make_ctx(make_cfg(raw)))
    assert mode(server_dir / "config.yaml") == 0o600
    assert mode(server_dir / "dex" / "config.yaml") == 0o644
    assert mode(server_dir / "dex") == 0o700
    assert mode(server_dir / ".env") == 0o600


def test_env_file_contents(server_dir, raw):
    deploy.phase_render(make_ctx(make_cfg(raw)))
    lines = (server_dir / ".env").read_text().splitlines()
    assert lines[0] == "# Generated by deploy.py from netbird.yaml. Do not edit."
    assert "COMPOSE_PROJECT_NAME=netbird" in lines
    values = dict(line.split("=", 1) for line in lines if "=" in line and not line.startswith("#"))
    assert re.fullmatch(r"[0-9a-f]{12}", values["CONFIG_YAML_SHA"])
    assert re.fullmatch(r"[0-9a-f]{12}", values["DEX_CONFIG_SHA"])


def test_local_auth_inverted(server_dir, raw):
    raw["server"]["local_auth"] = False
    deploy.phase_render(make_ctx(make_cfg(raw)))
    rendered = yaml.safe_load((server_dir / "config.yaml").read_text())
    assert rendered["server"]["auth"]["localAuthDisabled"] is True


def test_render_independent_of_cwd(server_dir, raw, tmp_path_factory, monkeypatch):
    elsewhere = tmp_path_factory.mktemp("elsewhere")
    monkeypatch.chdir(elsewhere)
    deploy.phase_render(make_ctx(make_cfg(raw)))
    assert (server_dir / "config.yaml").exists()
    assert list(elsewhere.iterdir()) == []


@pytest.mark.skipif(shutil.which("docker") is None, reason="docker not installed")
def test_compose_config_valid(server_dir, raw):
    deploy.phase_render(make_ctx(make_cfg(raw)))
    p = subprocess.run(
        ["docker", "compose", "--env-file", ".env", "-f", "docker-compose.yml",
         "config", "-q"],
        cwd=server_dir, capture_output=True, text=True)
    assert p.returncode == 0, p.stderr
